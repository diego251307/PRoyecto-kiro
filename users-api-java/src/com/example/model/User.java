package com.example.model;

// ==========================================================
// MODELO (entidad)
// Representa los datos de un usuario. Es un objeto simple que
// viaja entre todas las capas. No contiene lógica de negocio.
// ==========================================================
public class User {

    private int id;
    private String name;
    private String email;

    public User(int id, String name, String email) {
        this.id = id;
        this.name = name;
        this.email = email;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    @Override
    public String toString() {
        return "User{id=" + id + ", name='" + name + "', email='" + email + "'}";
    }
}
